#define PAGE2SEL ((soft_switches & (SOFTSW_80STORE | SOFTSW_PAGE_2)) == SOFTSW_PAGE_2)

volatile uint_fast32_t text_flasher_mask = 0;
static uint64_t next_flash_tick = 0;

void DELAYED_COPY_CODE(update_text_flasher)()
{
    uint64_t now = time_us_64();
    if(now > next_flash_tick)
    {
        text_flasher_mask ^= 0xff;

        switch(current_machine)
        {
            default:
            case MACHINE_II:
            case MACHINE_PRAVETZ:
                // fixed frequency generated by a NE555 timer circuit configured to 2.2Hz
                next_flash_tick = now + 227000u; // 2.2Hz/227ms cycle (independent of NTSC/PAL)
                break;
            case MACHINE_IIE:
            case MACHINE_IIE_ENH:
            case MACHINE_IIGS:
                // IIE used a fixed divisor based on a video counter inside the IOU,
                // and the resulting flashing frequency depended on PAL vs NTSC.
                if (IS_IFLAG(IFLAGS_PAL))
                    next_flash_tick = now + 312500u; // 1.6Hz/312.5ms cycle for PAL
                else
                    next_flash_tick = now + 250000u; // 2Hz/500ms cycle for NTSC
                break;
        }
    }
}

static inline uint_fast8_t char_text_bits(uint_fast8_t ch, uint_fast8_t glyph_line, uint32_t in_soft_switches, uint_fast32_t in_text_flasher_mask, bool in_language_switch)
{
    uint_fast8_t bits, invert;

    if((ch & 0x80) || (in_soft_switches & SOFTSW_ALTCHAR))
    {
        // normal / mousetext character
        invert = 0x00;
    } else {
        // flashing character or inverse character
        invert = (ch & 0x40) ? in_text_flasher_mask : 0x7f;
        ch = (ch & 0x3f) | 0x80;
    }

    uint_fast16_t LanguageOffset = (in_language_switch) ? 0x800 : 0x0;
    bits = character_rom[LanguageOffset | ((uint_fast16_t)ch << 3) | glyph_line];

    return (bits ^ invert) & 0x7f;
}

uint32_t* s_foreground_color = &tmds_mono_double_pixel[0];      //  White
uint32_t* s_background_color = &tmds_mono_double_pixel[3*3];    //  Black

uint32_t s_gs_fg_index = 0x000F * 3;     //  White
uint32_t s_gs_bg_index = 0;              //  Block

void DELAYED_COPY_CODE(render_text40_line)(const uint8_t *page, unsigned int line, uint8_t in_color_mode, bool gs_mode)
{
    const uint8_t *line_buf = (const uint8_t *)(page + ((line & 0x7) << 7) + (((line >> 3) & 0x3) * 40));

    if (gs_mode)
    {
        //  Setup the fg amd bg colors for the IIgs
        s_foreground_color = &tmds_lorescolor[s_gs_fg_index];
        s_background_color = &tmds_lorescolor[s_gs_bg_index];
    }
    else
    {
        //  Setup the fg amd bg colors
        s_foreground_color = &tmds_mono_double_pixel[in_color_mode*3];
        s_background_color = &tmds_mono_double_pixel[3*3];
    }

    for(uint glyph_line=0; glyph_line < 8; glyph_line++)
    {
        dvi_get_scanline(tmdsbuf);
        dvi_scanline_rgb560(tmdsbuf, tmdsbuf_red, tmdsbuf_green, tmdsbuf_blue);

        for(uint col=0; col < 40; )
        {
            // Grab 14 pixels from the next two characters
            uint32_t bits;
            bits  = char_text_bits(line_buf[col++], glyph_line, s_render_soft_switches, text_flasher_mask, s_render_language_switch);
            bits |= char_text_bits(line_buf[col++], glyph_line, s_render_soft_switches, text_flasher_mask, s_render_language_switch) << 7;

            // Translate bits into a pair of pixels
            for(int i=0; i < 14; i++)
            {
                uint32_t* tmds_double_pixel;

                if ((bits & 1)==0)
                    tmds_double_pixel = s_background_color;
                else
                    tmds_double_pixel = s_foreground_color;
                
                *(tmdsbuf_red++)   = tmds_double_pixel[0];
                *(tmdsbuf_green++) = tmds_double_pixel[1];
                *(tmdsbuf_blue++)  = tmds_double_pixel[2];
                bits >>= 1;
            }
        }
        dvi_send_scanline(tmdsbuf);
    }
}

#define ADD_LORES_PIXEL(color3) { \
    uint32_t* pTmds = &tmds_lorescolor[color3]; \
    *(tmdsbuf_red++)   = *(pTmds++); \
    *(tmdsbuf_green++) = *(pTmds++); \
    *(tmdsbuf_blue++)  = *pTmds; \
}

void DELAYED_COPY_CODE(render_color_text40_line)(unsigned int line, uint32_t in_soft_switches)
{
    const uint16_t xofs = ((line & 0x7) << 7) + (((line >> 3) & 0x3) * 40);
    const uint32_t *line_buf  = (const uint32_t *)(text_p1 + xofs);
    const uint32_t *color_buf = (const uint32_t *)(text_p3 + xofs);

    for(uint glyph_line=0; glyph_line < 8; glyph_line++)
    {
        dvi_get_scanline(tmdsbuf);
        dvi_scanline_rgb560(tmdsbuf, tmdsbuf_red, tmdsbuf_green, tmdsbuf_blue);

        for(uint col=0; col < 10; col++)
        {
            // grab 4 characters and color bytes
            uint32_t chars  = line_buf[col];
            uint32_t colors = color_buf[col];

            // process 4 characters
            for (uint c=0;c<4;c++)
            {
                // Grab 7 pixels from the next character
                uint32_t bits  = char_text_bits(chars&0xff, glyph_line, in_soft_switches, text_flasher_mask, s_render_language_switch);
                chars >>= 8;
                uint8_t foreground_color3 = ((colors >> 4) & 0xf)*3;
                uint8_t background_color3 = ((colors     ) & 0xf)*3;
                colors >>= 8;

                // Translate each pair of bits into a pair of pixels
                for(int i=0; i < 7; i++)
                {
                    ADD_LORES_PIXEL((bits & 0x1) ? foreground_color3 : background_color3);
                    bits >>= 1;
                }
            }
        }

        dvi_send_scanline(tmdsbuf);
    }
}

void DELAYED_COPY_CODE(render_text80_line)(const uint8_t *page_a, const uint8_t *page_b, unsigned int line, uint8_t in_color_mode, bool gs_mode)
{
    uint line_offset = ((line & 0x7) << 7) + (((line >> 3) & 0x3) * 40);
    const uint8_t *line_buf_a = (const uint8_t *) (page_a + line_offset);
    const uint8_t *line_buf_b = (const uint8_t *) (page_b + line_offset);

    uint8_t color_offset = in_color_mode*12;    //  For non-GS

    uint32_t* tmds_double_pixel = tmds_lores_single_pixel;

    if (gs_mode)
    {
        //  Base = ((((bg * 16) + fg) * 4) * 3) + (cfg_color_style * (3*16*16*4))
        tmds_double_pixel = &tmds_lores_single_pixel[(((s_gs_bg_index * (16 * 4)) + (s_gs_fg_index * 4))) + (cfg_color_style * (3*16*16*4))];
    }

    for(uint glyph_line=0; glyph_line < 8; glyph_line++)
    {
        dvi_get_scanline(tmdsbuf);
        dvi_scanline_rgb560(tmdsbuf, tmdsbuf_red, tmdsbuf_green, tmdsbuf_blue);

        for(uint col=0; col < 40;)
        {
            // Grab 14 pixels from the next two characters
            uint32_t bits;
            bits  = char_text_bits(line_buf_a[col], glyph_line, s_render_soft_switches, text_flasher_mask, s_render_language_switch) << 7;
            bits |= char_text_bits(line_buf_b[col], glyph_line, s_render_soft_switches, text_flasher_mask, s_render_language_switch);
            col++;

            if (gs_mode)
            {
                // Translate each pair of bits into a pair of single pixels
                for(int i=0; i < 7; i++)
                {
                    uint32_t symbol = (bits & 3) * 3;
                    *(tmdsbuf_red++)   = tmds_double_pixel[symbol+0];
                    *(tmdsbuf_green++) = tmds_double_pixel[symbol+1];
                    *(tmdsbuf_blue++)  = tmds_double_pixel[symbol+2];
                    bits >>= 2;
                }
            }
            else
            {
                // Translate each pair of bits into a pair of double pixels
                for(int i=0; i < 7; i++)
                {
                    char symbol = (bits&3) + color_offset;
                    *(tmdsbuf_blue++)  = tmds_mono_pixel_pair[symbol+8];
                    *(tmdsbuf_green++) = tmds_mono_pixel_pair[symbol+4];
                    *(tmdsbuf_red++)   = tmds_mono_pixel_pair[symbol+0];
                    bits >>= 2;
                }
            }
        }
        dvi_send_scanline(tmdsbuf);
    }
}

void DELAYED_COPY_CODE(render_mixed_text)()
{
    if((s_render_internal_flags & IFLAGS_VIDEO7) && ((s_render_soft_switches & (SOFTSW_80STORE | SOFTSW_80COL | SOFTSW_DGR)) == (SOFTSW_80STORE | SOFTSW_DGR)))
    {
        if (!mono_rendering)
        {
            for(uint line=20; line < 24; line++)
            {
                render_color_text40_line(line, s_render_soft_switches);
            }
            return;
        }
    }

    // monochrome rendering
    {
        const bool page2 = PAGE2SEL;
        const uint8_t *pageA = (const uint8_t *)(page2 ? text_p2 : text_p1);
        uint8_t cmode = (mono_rendering) ? color_mode : 0; /* white */

        if(s_render_soft_switches & SOFTSW_80COL)
        {
            // 80 column mode rendering
            const uint8_t *pageB = (const uint8_t *)(page2 ? text_p4 : text_p3);
            for(uint line=20; line < 24; line++)
            {
                render_text80_line(pageA, pageB, line, cmode, ((IS_IFLAG(IFLAGS_IIGS_REGS)) && (mono_rendering == false)));
            }
        }
        else
        {
            // 40 column mode rendering
            for(uint line=20; line < 24; line++)
            {
                render_text40_line(pageA, line, cmode, ((IS_IFLAG(IFLAGS_IIGS_REGS)) && (mono_rendering == false)));
            }
        }
    }
}

void DELAYED_COPY_CODE(render_text)(uint32_t in_internal_flags, uint32_t in_soft_switches)
{
    if((in_internal_flags & IFLAGS_VIDEO7) && ((in_soft_switches & (SOFTSW_80STORE | SOFTSW_80COL | SOFTSW_DGR)) == (SOFTSW_80STORE | SOFTSW_DGR)))
    {
        if (!mono_rendering)
        {
            for(uint line=0; line < 24; line++)
            {
                render_color_text40_line(line, in_soft_switches);
            }
            return;
        }
    }
    else
    {
        color_support = false;
    }

    // monochrome rendering
    {
        const bool page2 = PAGE2SEL;
        const uint8_t *pageA = (const uint8_t *)(page2 ? text_p2 : text_p1);

        if(in_soft_switches & SOFTSW_80COL)
        {
            // 80 column mode rendering
            const uint8_t *pageB = (const uint8_t *)(page2 ? text_p4 : text_p3);
            for(uint line=0; line < 24; line++)
            {
                render_text80_line(pageA, pageB, line, color_mode, ((IS_IFLAG(IFLAGS_IIGS_REGS)) && (mono_rendering == false)));
            }
        }
        else
        {
            // 40 column mode rendering
            for(uint line=0; line < 24; line++)
            {
                render_text40_line(pageA, line, color_mode, ((IS_IFLAG(IFLAGS_IIGS_REGS)) && (mono_rendering == false)));
            }
        }
    }
}
